"""Generate/check hideout recipes against live source loot; never deploys map data."""
from pathlib import Path
import argparse
import json
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "docs/npc-overhaul/tools"))
import fts_delivery_balance as supply

REPORT = ROOT / "docs/balance/hideout-crates.md"
MAP_NAMES = ("Swamps", "Garbage", "Waystation", "Pripyat")


def render():
    data = supply.snapshot()
    rates, _, _ = supply.estimate(data)
    snapshot = json.loads(subprocess.run(
        ["luatex", "--luaonly", "docs/balance/hideout_snapshot.lua"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout)
    recipes = snapshot["recipes"]
    items = set()
    for family, levels in recipes.items():
        previous = 0
        for level in levels:
            assert level["price"] > previous, family
            previous = level["price"]
            for group in level["groups"]:
                items.update(group["items"])
                for item in group["items"]:
                    assert item in data["items"], item
                    allowed = supply.MAPS[:2] if level["level"] < 6 else supply.MAPS[:3] if level["level"] < 10 else supply.MAPS
                    assert sum(sum(v[0] for v in rates[m].get(item, {}).values()) for m in allowed) > 0, item
    lines = ["# Hideout crate recipes", "",
             "Generated by `python3 docs/balance/hideouts.py --write` from active recipes, loot pools and FTS presets.",
             "Use `--check` to verify the report without changing it. No FTS setup or saved-state changes run.", "",
             "All three contacts use identical personal recipes. Squad crates multiply every raw material cost and ruble charge by three.",
             "Common groups accept mixtures; nuts cost three raw units per batch, bolts four, and other inputs one.",
             "Each crate requires a free 2×2 space in the main inventory before assembly.", "",
             "## Personal recipe matrix", "",
             "Fasteners accept nuts, bolts, nails or screws. Packing materials are selected from the family list below.", "",
             "| Level | Fastener batches | Packing batches | Early rare | Waystation | Pripyat components | General RU | Ammo RU | Medical/fridge RU | Gear/weapon RU |",
             "| --- | ---: | ---: | ---: | ---: | --- | ---: | ---: | ---: | ---: |"]
    for i, recipe in enumerate(recipes["general"]):
        groups = recipe["groups"]
        rare = groups[2]["quantity"] if len(groups) > 2 else 0
        regional = groups[3]["quantity"] if len(groups) > 3 else 0
        late = ", ".join(item for group in groups[4:] for item in group["items"]) or "—"
        prices = [recipes[f][i]["price"] for f in ("general", "ammo", "medical", "gear")]
        lines.append(f"| {i + 1} | {groups[0]['quantity']} | {groups[1]['quantity']} | {rare} | {regional} | {late} | "
                     + " | ".join(f"{p:,}" for p in prices) + " |")
    lines += ["", "## Family materials", "",
              "| Family | Common packing alternatives | Early rare from level 4 | Waystation from level 6 |",
              "| --- | --- | --- | --- |"]
    for family, levels in sorted(recipes.items()):
        groups = levels[-1]["groups"]
        lines.append(f"| {family} | {', '.join(groups[1]['items'])} | {groups[2]['items'][0]} | {groups[3]['items'][0]} |")
    lines += ["", "## Source evidence", "",
              "Numbers are comparative full-map collection opportunities per modeled hour, not player earnings or guaranteed drops.",
              "They include loose items, boxes and cycling containers. Live placements, competition and missed spawns can change supply.",
              "Waystation supplies have very small early-map cache exposure; the recipes introduce them only at level 6.",
              "The three Pripyat components have no quantified earlier-map source.", "",
              "| Item | Swamps | Garbage | Waystation | Pripyat |", "| --- | ---: | ---: | ---: | ---: |"]
    for item in sorted(items):
        values = [sum(v[0] for v in rates[m].get(item, {}).values()) for m in supply.MAPS]
        lines.append(f"| `{item}` | " + " | ".join(f"{v:.2f}" for v in values) + " |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.write:
        REPORT.write_text(text)
    elif args.check:
        if not REPORT.exists() or REPORT.read_text() != text:
            raise SystemExit("Hideout recipe report is stale; run with --write")
        print("PASS: hideout recipes and source evidence match current definitions")
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
