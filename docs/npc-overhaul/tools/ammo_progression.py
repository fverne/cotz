#!/usr/bin/env python3
"""Author ammunition stages from the first use of each regular load in the gun chains."""
import argparse
from fractions import Fraction
from pathlib import Path
import re
import runpy

ROOT = Path(__file__).resolve().parents[3]
DEFINITIONS = ROOT / "gamemodes/ix_cotz/plugins/townnpcs/definitions"
REPORT = ROOT / "docs/npc-overhaul/ammo-progression.md"
LEGACY_MARKER = "-- Ammunition price-band order; generated by docs/npc-overhaul/tools/ammo_progression.py."
REGULAR_MARKER = "-- Regular ammunition chain; generated by docs/npc-overhaul/tools/ammo_progression.py."
MARKER = "-- Ammunition stage order; generated by docs/npc-overhaul/tools/ammo_progression.py."


def ammunition():
    result = {}
    for path in sorted((ROOT / "gamemodes/ix_cotz/schema/items/newammo").glob("sh_*.lua")):
        source = path.read_text()
        values = {}
        for field in ("price", "ammoAmount"):
            match = re.search(r"^ITEM\." + field + r"\s*=\s*(\d+(?:\.\d+)?)\s*(?://[^\n]*)?$",
                              source, re.M)
            if not match or Fraction(match[1]) <= 0:
                raise ValueError(f"{path.name}: expected positive literal {field}")
            values[field] = Fraction(match[1])
        item = path.stem[3:]
        regular = item[:-2] if item.endswith(("ap", "hp")) else item
        if item in {"12gaugedt", "12gaugesg", "12gaugemg", "12gaugetr"}:
            regular = "12gauge"
        result[item] = {**values, "cost": values["price"] / values["ammoAmount"], "regular": regular}
    return result


def regular_order(data, ammo):
    source = (ROOT / "gamemodes/ix_cotz/schema/libs/sh_weapontables.lua").read_text()
    ammo_types = dict(re.findall(r'ammotypes\["([^"]+)"\] = \{uID = "([^"]+)"', source))
    first_uses = {}
    for chain_index, chain in enumerate(data["chains"]):
        first = ROOT / f"gamemodes/ix_cotz/schema/items/newweapons/sh_{chain[0]}.lua"
        if len(chain) <= 2 or not first.exists():
            continue
        for position, item in enumerate(chain, 1):
            path = ROOT / f"gamemodes/ix_cotz/schema/items/newweapons/sh_{item}.lua"
            source = path.read_text()
            weapon_class = re.search(r'ITEM.class\s*=\s*"([^"]+)"', source)
            price = re.search(r"ITEM.price\s*=\s*(\d+)", source)
            if not weapon_class or not price:
                raise ValueError(f"{path}: expected literal weapon class and price")
            weapon = ROOT / f"lua/weapons/{weapon_class[1]}/shared.lua"
            default = re.search(r'SWEP.Primary.Ammo\s*=\s*"([^"]+)"', weapon.read_text())
            if not default:
                raise ValueError(f"{weapon}: expected literal primary ammunition")
            # .410 bore has its own item, despite being encoded as a .45 ACP attachment load.
            regular = "45acp41" if default[1] == ".45 ACP -41-" else ammo_types.get(default[1])
            if regular not in ammo or ammo[regular]["regular"] != regular:
                raise ValueError(f"{weapon}: unknown regular ammunition {default[1]}")
            key = (position, int(price[1]), chain_index, item)
            if regular not in first_uses or key < first_uses[regular]:
                first_uses[regular] = key
    regulars = {item for item, entry in ammo.items() if entry["regular"] == item}
    ordered = sorted(first_uses, key=first_uses.get)
    ordered.extend(sorted(regulars - first_uses.keys()))
    return ordered, first_uses


def allocations(data, ammo):
    regulars, _ = regular_order(data, ammo)
    ranks = {item: index for index, item in enumerate(regulars)}
    last_stage = 3 * (len(regulars) - 1) + 2
    routes, orders = {}, {}
    for slug, contact in data["contacts"].items():
        steps = contact["progression"]
        routes[slug] = {}
        owned_ranks = [ranks[ammo[item]["regular"]]
                       for item in contact["catalogue"] if item in ammo]
        first_rank = min(owned_ranks, default=0)
        for item in contact["catalogue"]:
            if item not in ammo:
                continue
            entry = ammo[item]
            stage = 2 if item.endswith("ap") else 1 if item != entry["regular"] else 0
            rank = ranks[entry["regular"]] - first_rank
            regular_index = min(len(steps) - 3, (3 * rank) * (len(steps) - 1) // last_stage)
            index = regular_index
            if stage:
                index = max(regular_index + stage, (3 * rank + stage) * (len(steps) - 1) // last_stage)
            routes[slug][item] = steps[index]["id"]
        order = sorted(set(routes[slug].values()), key=lambda step: int(step[2:]))
        if order:
            orders[slug] = order
    return routes, orders


def order_source(regulars, orders):
    regular_lines = [REGULAR_MARKER, "PLUGIN.regularAmmoChain = {"]
    regular_lines.extend('\t"' + item + '",' for item in regulars)
    regular_lines.extend(["}", ""])
    lines = [MARKER, "PLUGIN.ammoUnlockOrder = {"]
    for slug, steps in sorted(orders.items()):
        lines.append('\t["' + slug + '"] = {')
        lines.extend('\t\t"' + step + '",' for step in steps)
        lines.append("\t},")
    return "\n".join(regular_lines + lines + ["}", ""])


def render(data, ammo, routes):
    regulars, first_uses = regular_order(data, ammo)
    ranks = {item: index for index, item in enumerate(regulars)}
    lines = ["# Ammunition progression from gun availability", "",
             "Generated with `python3 docs/npc-overhaul/tools/ammo_progression.py --write`.", "",
             "`PLUGIN.regularAmmoChain` contains every regular load, excluding AP, HP and special shotgun variants.",
             "The five parallel gun chains are compared by position, then gun price, chain order and item ID.",
             "The first default SWEP ammunition use determines each calibre's place. Unused calibres follow alphabetically.",
             "This compares definition positions, not completion time through the shared contact prerequisites.",
             "Regular ranks replace the previous price bands; regular, HP and AP stages are scaled to each seller's tree.",
             "HP requires regular ammunition. AP additionally requires local HP when available, including equal-price variants.",
             "Each vendor's ammunition stages require its preceding stage, so sibling story branches cannot bypass the order.",
             "The approved plan has no starting sale supplies. No box prices, round counts or damage values are changed.", "",
             "AP, HP and special shotgun variants are outside the regular chain and retain local counterpart prerequisites.",
             "They share their regular load's rank, with later upgrade stages. Prices below are reference values only.",
             "The legacy ID `45acp41` is .410 bore, a separate cartridge rather than a .45 ACP upgrade.", "",
             "## Regular chain", "", " → ".join(regulars), "",
             "| Regular load | First gun | Position |", "| --- | --- | ---: |"]
    for item in regulars:
        first = first_uses.get(item)
        lines.append(f"| {item} | {first[3] if first else 'Unaccounted: appended'} | {first[0] if first else '—'} |")
    lines += ["", "## Seller allocations", "",
             "| Item | Box price | Rounds | Price per round | Regular counterpart | Seller: milestone |",
             "| --- | ---: | ---: | ---: | --- | --- |"]
    for item, entry in sorted(ammo.items(), key=lambda pair: (ranks[pair[1]["regular"]], pair[1]["cost"], pair[0])):
        sellers = [f"{slug}: {r[item]}" for slug, r in sorted(routes.items()) if item in r]
        supplies = [slug + ": ungated" for slug, c in sorted(data["contacts"].items())
                    if item in c["supplies"] and item not in routes[slug]]
        lines.append(f"| {item} | {entry['price']} | {entry['ammoAmount']} | {float(entry['cost']):.4f} | "
                     f"{entry['regular']} | {'; '.join(sellers + supplies)} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--write", action="store_true")
    modes.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ledger = runpy.run_path(str(ROOT / "docs/npc-overhaul/tools/progression_rewards.py"))
    data = ledger["snapshot"]()
    ammo = ammunition()
    regulars, _ = regular_order(data, ammo)
    routes, orders = allocations(data, ammo)
    errors = []
    for slug, allocations_for_contact in routes.items():
        path = DEFINITIONS / ("sh_" + slug.replace("-", "_") + ".lua")
        source = path.read_text()
        for item, step in allocations_for_contact.items():
            current = data["contacts"][slug]["catalogue"][item]["step"]
            if current != step:
                errors.append(f"{slug}/{item}: {current}, expected {step}")
                source, count = re.subn(r'(\["' + re.escape(item) + r'"\] = \{step = ")[^"]+',
                                        lambda match: match[1] + step, source)
                assert count == 1
        if args.write:
            path.write_text(source)
    equipment = DEFINITIONS / "sh_equipment.lua"
    source = equipment.read_text().split(REGULAR_MARKER)[0].split(LEGACY_MARKER)[0].split(MARKER)[0]
    source = source.rstrip() + "\n\n" + order_source(regulars, orders)
    report = render(data, ammo, routes)
    if args.write:
        equipment.write_text(source)
        REPORT.write_text(report)
    else:
        if equipment.read_text() != source:
            errors.append("Ammunition stage prerequisites are stale")
        if REPORT.read_text() != report:
            errors.append("Ammunition progression report is stale")
        if errors:
            raise SystemExit("\n".join(errors))
    print(f"Checked {len(ammo)} ammunition definitions and {sum(map(len, routes.values()))} purchase routes")


if __name__ == "__main__":
    main()
