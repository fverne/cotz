#!/usr/bin/env python3
"""Author and verify town ammunition price bands using price / ammoAmount, without changing prices."""
import argparse
from fractions import Fraction
from pathlib import Path
import re
import runpy

ROOT = Path(__file__).resolve().parents[3]
DEFINITIONS = ROOT / "gamemodes/ix_cotz/plugins/townnpcs/definitions"
REPORT = ROOT / "docs/npc-overhaul/ammo-progression.md"
MARKER = "-- Ammunition price-band order; generated by docs/npc-overhaul/tools/ammo_progression.py."
BAND_COUNT = 12


def ammunition():
    result = {}
    for path in sorted((ROOT / "gamemodes/ix_cotz/schema/items/newammo").glob("sh_*.lua")):
        source = path.read_text()
        values = {}
        for field in ("price", "ammoAmount"):
            match = re.search(r"^ITEM\." + field + r"\s*=\s*(\d+(?:\.\d+)?)\s*(?://[^\n]*)?$",
                              source, re.M)
            if not match or Fraction(match[1]) <= 0:
                raise ValueError(f"{path.name}: expected positive literal {field}")
            values[field] = Fraction(match[1])
        item = path.stem[3:]
        regular = item[:-2] if item.endswith(("ap", "hp")) else item
        if item in {"12gaugedt", "12gaugesg", "12gaugemg", "12gaugetr"}:
            regular = "12gauge"
        result[item] = {**values, "cost": values["price"] / values["ammoAmount"], "regular": regular}
    return result


def allocations(data, ammo):
    # Compare every calibre against the same global scale, rather than restarting each family at step 1.
    costs = sorted({max(entry["cost"], ammo[entry["regular"]]["cost"]) for entry in ammo.values()})
    bands = {cost: index * BAND_COUNT // len(costs) for index, cost in enumerate(costs)}
    routes, orders = {}, {}
    for slug, contact in data["contacts"].items():
        steps = contact["progression"]
        routes[slug] = {}
        for item in contact["catalogue"]:
            if item not in ammo:
                continue
            entry = ammo[item]
            regular = ammo[entry["regular"]]
            # Counterpart ordering takes precedence over anomalously cheaper variant boxes.
            variant = item != entry["regular"]
            band = bands[max(entry["cost"], regular["cost"])]
            regular_index = min(len(steps) - 2, (2 * band) * (len(steps) - 1) // 23)
            index = regular_index
            if variant:
                index = max(regular_index + 1, (2 * band + 1) * (len(steps) - 1) // 23)
            routes[slug][item] = steps[index]["id"]
        order = sorted(set(routes[slug].values()), key=lambda step: int(step[2:]))
        if order:
            orders[slug] = order
    return routes, orders


def order_source(orders):
    lines = [MARKER, "PLUGIN.ammoUnlockOrder = {"]
    for slug, steps in sorted(orders.items()):
        lines.append('\t["' + slug + '"] = {')
        lines.extend('\t\t"' + step + '",' for step in steps)
        lines.append("\t},")
    return "\n".join(lines + ["}", ""])


def render(data, ammo, routes):
    lines = ["# Ammunition progression by price per round", "",
             "Generated with `python3 docs/npc-overhaul/tools/ammo_progression.py --write`.", "",
             "The cost is the concrete item's `price / ammoAmount`, matching the ammunition base's GetPrice.",
             "Twelve global price bands each have regular and upgraded-load stages, scaled to the contact's tree.",
             "Different prices may share a band. AP and HP at equal prices are parallel upgrades; neither requires the other.",
             "Each vendor's ammunition stages require its preceding stage, so sibling story branches cannot bypass the order.",
             "Regional ungated basic supplies remain available. No box prices, round counts or damage values are changed.", "",
             "Variants always follow their regular counterpart. Special 12-gauge loads and 14.5 mm variants currently cost",
             "less per round than the regular load; they use the regular load's price band to preserve that upgrade rule.",
             "The legacy ID `45acp41` is .410 bore, a separate cartridge rather than a .45 ACP upgrade.", "",
             "| Item | Box price | Rounds | Price per round | Regular counterpart | Seller: milestone |",
             "| --- | ---: | ---: | ---: | --- | --- |"]
    for item, entry in sorted(ammo.items(), key=lambda pair: (pair[1]["cost"], pair[0])):
        sellers = [f"{slug}: {r[item]}" for slug, r in sorted(routes.items()) if item in r]
        supplies = [slug + ": ungated" for slug, c in sorted(data["contacts"].items())
                    if item in c["supplies"] and item not in routes[slug]]
        lines.append(f"| {item} | {entry['price']} | {entry['ammoAmount']} | {float(entry['cost']):.4f} | "
                     f"{entry['regular']} | {'; '.join(sellers + supplies)} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--write", action="store_true")
    modes.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ledger = runpy.run_path(str(ROOT / "docs/npc-overhaul/tools/progression_rewards.py"))
    data = ledger["snapshot"]()
    ammo = ammunition()
    routes, orders = allocations(data, ammo)
    errors = []
    for slug, allocations_for_contact in routes.items():
        path = DEFINITIONS / ("sh_" + slug.replace("-", "_") + ".lua")
        source = path.read_text()
        for item, step in allocations_for_contact.items():
            current = data["contacts"][slug]["catalogue"][item]["step"]
            if current != step:
                errors.append(f"{slug}/{item}: {current}, expected {step}")
                source, count = re.subn(r'(\["' + re.escape(item) + r'"\] = \{step = ")[^"]+',
                                        lambda match: match[1] + step, source)
                assert count == 1
        if args.write:
            path.write_text(source)
    equipment = DEFINITIONS / "sh_equipment.lua"
    source = equipment.read_text().split(MARKER)[0].rstrip() + "\n\n" + order_source(orders)
    report = render(data, ammo, routes)
    if args.write:
        equipment.write_text(source)
        REPORT.write_text(report)
    else:
        if equipment.read_text() != source:
            errors.append("Ammunition stage prerequisites are stale")
        if REPORT.read_text() != report:
            errors.append("Ammunition price report is stale")
        if errors:
            raise SystemExit("\n".join(errors))
    print(f"Checked {len(ammo)} ammunition definitions and {sum(map(len, routes.values()))} purchase routes")


if __name__ == "__main__":
    main()
